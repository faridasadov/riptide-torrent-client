function rtSiteIcon(name) {
  const path = RT_SITE_ICONS[name];
  if (!path) return "";
  return `<svg class="rt-ico" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

document.querySelectorAll("[data-site-icon]").forEach((el) => {
  const label = el.textContent.trim();
  el.innerHTML = `${rtSiteIcon(el.dataset.siteIcon)}${label ? `<span>${label}</span>` : ""}`;
});
